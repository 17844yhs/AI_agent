import torch

a = torch.tensor([[1, 2], [3, 4]])  # 形状：(2, 2)
b = torch.tensor([[5, 6], [7, 8]])  # 形状：(2, 2)
c = torch.tensor([[5], [6]])  # 形状：(2, 1)
d = torch.tensor([[1,2,3]]) # 形状：(1, 3)

# 广播机制规则：
# 维度相同
print(f'张量a+b:{a+b}')

# 维度不同，但是其中一个张量的维度是1
# 按照1的维度进行广播，  将[[5], [6]] 广播成[[5, 5], [6, 6]]
print(f'张量a+c:{a+c}')

# 维度不同
print(f'张量a+d:{a+d}')  # 报错